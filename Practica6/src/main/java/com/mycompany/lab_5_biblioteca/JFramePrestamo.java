    private void cargarCombos() {
        Estudiante.removeAllItems();
        Libro.removeAllItems();
        if (Principal.listaEstudiantes.isEmpty()) {
            Estudiante msg=new Estudiante("no hay estudiantes","");
            Estudiante.addItem(msg);
            Estudiante.setEnabled(false);
        } else {
            for (Estudiante e : Principal.listaEstudiantes) {
                Estudiante.addItem(e);
            }
        }

        if (Principal.listaLibros.isEmpty()) {
            Libro msg=new Libro("","no hay Libros",(new String[]{""}));
            Libro.addItem(msg);
            Libro.setEnabled(false);
        } else {
            for (Libro l : Principal.listaLibros) {
                boolean prestado = Principal.listaPrestamos.stream().anyMatch(p -> p.getLibro().equals(l));
                
                if (!prestado) {
                    Libro.addItem(l);
                }
            }
            if (Libro.getItemCount() == 0) {
                Libro msg=new Libro("","Todos los libros estan prestados",(new String[]{""}));
                Libro.addItem(msg);
                Libro.setEnabled(false);
            }
        }
    }

