    private void GuardadoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_GuardadoActionPerformed
        Estudiante est = (Estudiante) Estudiante.getSelectedItem();
        Libro libro = (Libro) Libro.getSelectedItem();
        String fechaP = FechaP.getText();
        String fechaD = FechaD.getText();

        if (est == null || libro == null ||
            est.toString().startsWith("no hay estudiante") || libro.toString().startsWith("No hay libro")) {
            lblMensaje.setForeground(java.awt.Color.RED);
            lblMensaje.setText("Selecciona un estudiante y un libro");
            return;
        }

        if (fechaP.isEmpty() || fechaD.isEmpty()) {
            lblMensaje.setForeground(java.awt.Color.RED);
            lblMensaje.setText("Las fechas no pueden estar vacias.");
            return;
        }

        Prestamo p = new Prestamo(fechaP, fechaD, est, libro);
        Principal.listaPrestamos.add(p);

        lblMensaje.setForeground(java.awt.Color.green);
        lblMensaje.setText("Se realizo el prestamo del libro " + libro.getTitulo() + " a el estudiante " + est.getNombre());

        cargarCombos();
    }//GEN-LAST:event_GuardadoActionPerformed

    

